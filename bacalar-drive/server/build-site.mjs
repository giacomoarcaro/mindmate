// Copies ../dist into ./site as numbered .bin files and writes src/site.ts, so the game is
// bundled inside the Worker (the asset upload API cannot be used from every environment).
import { readdirSync, statSync, mkdirSync, rmSync, copyFileSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
const DIST = '../dist', SITE = './site';
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8' };
rmSync(SITE, { recursive: true, force: true });
mkdirSync(SITE);
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else files.push(p); } };
walk(DIST);
let imports = '', table = '';
files.forEach((f, i) => {
  copyFileSync(f, join(SITE, `f${i}.bin`));
  const path = '/' + relative(DIST, f).split('\\').join('/');
  imports += `import f${i} from '../site/f${i}.bin';\n`;
  table += `  ${JSON.stringify(path)}: { body: f${i}, type: ${JSON.stringify(TYPES[extname(f)] ?? 'application/octet-stream')}, hashed: ${/assets\//.test(path)} },\n`;
});
writeFileSync('src/site.ts', `// generated by build-site.mjs\n${imports}\nexport const SITE: Record<string, { body: ArrayBuffer; type: string; hashed: boolean }> = {\n${table}};\n`);
console.log(`site: ${files.length} files`);
